// This object generate content of H file. The content is affected by generating C file.
var ClockConfigH = {
  // Output writer
  writer: null,
  
  // Status "is extern scg_sys_clk_config_t generated". generate() initialize to false. C file generating script can set to true.
  isScgConfigExtern: new Object(),
  // Status "is extern scg_sirc_config_t generated". generate() initialize to false. C file generating script can set to true.
  isSircConfigExtern: new Object(),
  // Status "is extern scg_sosc_config_t generated". generate() initialize to false. C file generating script can set to true.
  isSoscConfigExtern: new Object(),
  // Status "is extern scg_firc_config_t generated". generate() initialize to false. C file generating script can set to true.
  isFircConfigExtern: new Object(),
  // Status "is extern vbat_osc_config_t generated". generate() initialize to false. C file generating script can set to true.
  isVbatConfigExtern: new Object(),
  
  // references on define block instances for "common" and for each configufration
  defineBlockH: new Object(),
  // references on define block positions for "common" and for each configuration
  defineBlockHPosition: new Object(),
  // references on extern scg_sys_clk_config_t places for each configuration
  scgConfigExternPosition: new Object(),
  // references on extern scg_sirc_config_t places for each configuration
  sircConfigExternPosition: new Object(),
  // references on extern scg_firc_config_t places for each configuration
  fircConfigExternPosition: new Object(),
  // references on extern scg_sosc_config_t places for each configuration
  soscConfigExternPosition: new Object(),
  // references on extern vbat_osc_config_t places for each configuration
  vbatConfigExternPosition: new Object(),
  
  // generate h file content and create insertions for definitions
  generate: function(writer) {
    // safe output writer
    this.writer = writer;

/*    
    HWriter.write(CommonHeaderText());
    HWriter.write("");
*/
    HWriter.writeLines([
    "/***********************************************************************************************************************",
    " * This file was generated by the MCUXpresso Config Tools. Any manual edits made to this file",
    " * will be overwritten if the respective MCUXpresso Config Tools is used to update this file.",
    " **********************************************************************************************************************/",
    "",
    "#ifndef _CLOCK_CONFIG_H_",
    "#define _CLOCK_CONFIG_H_",
    "",
    "#include \"fsl_common.h\"",
    "",
    ]);
    //Common definitions
    this.defineBlockHPosition["common"] = HWriter.write(null); 
    HWriter.writeLines(OutputUtils.getDefinitionIntro(), this.defineBlockHPosition["common"]);
    this.defineBlockH["common"] = new DefineBlock();

    var theSame = HwAbstr.isSettingSameInAllConfigurations("SCG.CLK_IN.outFreq", "sosc", "asInteger");
    if (theSame != null && theSame) {
      var values = HwAbstr.getSettingValuesForAllConfigurations("SCG.CLK_IN.outFreq", "sosc", "asInteger");
      this.defineBlockH["common"].addDefine("BOARD_XTAL0_CLK_HZ", values[0], "Board xtal0 frequency in Hz");
    }
  
    HWriter.writeLines([
    '/*******************************************************************************',
    ' ************************ BOARD_InitBootClocks function ************************',
    ' ******************************************************************************/',
    '',
    '#if defined(__cplusplus)',
    'extern "C" {',
    '#endif /* __cplusplus*/',
    '',
    '/*!',
    ' * @brief This function executes default configuration of clocks.',
    ' *',
    ' */',
    'void BOARD_InitBootClocks(void);',
    '',
    '#if defined(__cplusplus)',
    '}',
    '#endif /* __cplusplus*/',
    '']);

    function printOutputs(innerCfg, innerConfigID) {
      var defineValuePos = 55;
      var defineCommentPos = 70;
      var idSet = innerCfg["getClockOutputSettings"]();
      var idSetNew = new Array();
      if ((idSet != null) && (idSet != undefined)) {
        HWriter.write("/* Clock outputs (values are in Hz): */");
        for (var si = 0; si < idSet.length; si++) {
          idSetNew[si] = idSet[si];
        }
        idSetNew = idSetNew.sort();
        for (var si = 0; si < idSet.length; si++) {
          var idName = idSetNew[si];
          var idUnifiedID = idSetNew[si];
          var idValue = innerCfg.getValueAsBigInteger(idSetNew[si]); 
          var idDefaultValue = innerCfg.getDefaultValueAsText(idSetNew[si]);
          idName = idName.split(".outFreq").join("").toUpperCase().split(".");
          idName = idName[idName.length-1];          
          idUnifiedID = idUnifiedID.split(".outFreq").join("");
          var line = "#define " + innerConfigID.toUpperCase() + "_" +  idName;
          if ((line.length + 1) < defineValuePos) {
            line = line.concat(Array(defineValuePos - line.length).join(" "));
          } else {
            line += " ";
          }
          line += idValue.toString();          
          if (idValue > 0xFFFFFFFF) {
            line += "ULL";
          }
          else {
            line += "UL";
          }

          if ((line.length + 1) < defineCommentPos) {
            line = line.concat(Array(defineCommentPos - line.length).join(" "));
          } else {
            line += " ";
        }

          periphList = innerCfg.getClockOutputConsumers(idUnifiedID);
          periphStr = "";
          for (var index = 0; index < periphList.length; index++) {
            if (periphStr == "") {
              periphStr += periphList[index];
            } else {
              periphStr += ", " + periphList[index];
            }
          }
          if (periphStr == "") {
            periphStr = "N/A"  
          }
          line += "/* Clock consumers of " + idUnifiedID + " output : " + periphStr + " */";
          HWriter.write(line);        
        }
      }  
      else {
        HWriter.write(getFunction + "() returns null or undefined.");
      } 
    }

    //generate the header part for each configuration 
    for (var cfgIndex = 0; cfgIndex < Gen.configs.length; cfgIndex++) {
      var cfg = Gen.configs[cfgIndex];
      var configID = Gen.getConfigID(cfg);
      var prefixID = Gen.getPrefixID(cfg);
      var configName = cfg.getName();
      // clear status "is extern scg_sys_clk_config_t generated"
      this.isScgConfigExtern[configID] = false;
      // clear status "is extern scg_sirc_config_t generated"
      this.isSircConfigExtern[configID] = false;
      // clear status "is extern scg_sosc_config_t generated"
      this.isSoscConfigExtern[configID] = false;
      // clear status "is extern scg_firc_config_t generated"
      this.isFircConfigExtern[configID] = false;
      // clear status "is extern scg_vbat_config_t generated"
      this.isVbatConfigExtern[configID] = false;

      // write configuration introduction
      HWriter.writeLines(OutputUtils.getConfigurationIntro(cfg));
      // write definition introduction
      HWriter.writeLines(OutputUtils.getDefinitionIntro(cfg));

      this.defineBlockHPosition[configID] = HWriter.write(null); 
      // create block instance of #defines 
      this.defineBlockH[configID] = new DefineBlock();
      SDKMapper.setHWriterDefineContainer = this.defineBlockH[configID];   
      tmp = SDKMapper.getFieldValue(cfg, "coreClock");
      if (tmp != null) {
        this.defineBlockH[configID].addDefine(prefixID.toUpperCase() + "_CORE_CLOCK", tmp.value, tmp.description);
      }

      tmp = SDKMapper.getFieldValue(cfg, "roscClock");
      if (tmp != null) {
        this.defineBlockH[configID].addDefine(prefixID.toUpperCase() + "_ROSC_CLOCK", tmp.value, tmp.description);
      }

      // generate clock outputs defines with values in Hz
      printOutputs(cfg, prefixID);        
      HWriter.write("");

      // allocate place for extern scg_sys_clk_config_t 
      this.scgConfigExternPosition[configID] = HWriter.write(null);
      // allocate place for extern scg_sosc_config_t 
      this.soscConfigExternPosition[configID] = HWriter.write(null);
      // allocate place for extern scg_sirc_config_t 
      this.sircConfigExternPosition[configID] = HWriter.write(null);
      // allocate place for extern scg_firc_config_t 
      this.fircConfigExternPosition[configID] = HWriter.write(null);
      // allocate place for extern vbat_osc_config_t
      this.vbatConfigExternPosition[configID] = HWriter.write(null);

      HWriter.line("");  

      // write api introduction
      HWriter.writeLines(OutputUtils.getApiIntro(cfg));
      HWriter.writeLines([
      "#if defined(__cplusplus)",
      "extern \"C\" {",
      "#endif /* __cplusplus*/"]);
      HWriter.write("");
      HWriter.writeLines([
      "/*!",
      " * @brief This function executes configuration of clocks.",
      " *",
      " */"]);
      HWriter.write("void " + Gen.getConfigID(Gen.configs[cfgIndex]) + "(void);");
      HWriter.writeLines([
      "",
      "#if defined(__cplusplus)",
      "}",
      "#endif /* __cplusplus*/",
      "",
      ]);
    }
    HWriter.writeLines([
    "#endif /* _CLOCK_CONFIG_H_ */",
    "",
    ]);
  },
  
  //complete h file content, e.g. definition insertion
  complete: function(){
    // write common define block
    HWriter.writeLines(this.defineBlockH["common"].getDefineBlock().concat(""), this.defineBlockHPosition["common"]);
    for (var cfgIndex = 0; cfgIndex < Gen.configs.length; cfgIndex++) {
      var cfg = Gen.configs[cfgIndex];
      var configID = Gen.getConfigID(cfg);
      var prefixID = Gen.getPrefixID(cfg);
      var configName = cfg.getName();
      // write common define block
      HWriter.writeLines(this.defineBlockH[configID].getDefineBlock().concat(""), this.defineBlockHPosition[configID]);
      // extern scg_sys_clk_config_t
      if (this.isScgConfigExtern[configID]) {
        HWriter.writeLines([
        "/*! @brief SCG set for " + configName + " configuration.",
        " */",
        ], this.scgConfigExternPosition[configID]);
        HWriter.write("extern const scg_sys_clk_config_t g_sysClkConfig_" + prefixID + ";", this.scgConfigExternPosition[configID]);
      }

      // extern scg_sosc_config_t
      if (this.isSoscConfigExtern[configID]) {
        HWriter.writeLines([
        "/*! @brief System OSC set for " + configName + " configuration.",
        " */"
        ], this.soscConfigExternPosition[configID]);
        HWriter.write("extern const scg_sosc_config_t g_scgSysOscConfig_" + prefixID + ";", this.soscConfigExternPosition[configID]);
      }

      // extern scg_sirc_config_t
      if (this.isSircConfigExtern[configID]) {
        HWriter.writeLines([
        "/*! @brief SIRC set for " + configName + " configuration.",
        " */"
        ], this.sircConfigExternPosition[configID]);
        HWriter.write("extern const scg_sirc_config_t g_scgSircConfig_" + prefixID + ";", this.sircConfigExternPosition[configID]);
      }

      // extern scg_firc_config_t
      if (this.isFircConfigExtern[configID]) {
        HWriter.writeLines([
        "/*! @brief FIRC set for " + configName + " configuration.",
        " */"
        ], this.fircConfigExternPosition[configID]);
        HWriter.write("extern const scg_firc_config_t g_scgFircConfig_" + prefixID + ";", this.fircConfigExternPosition[configID]);
      }

      // extern ccm32k_osc_config_t
      // if (this.isCcm32kConfigExtern[configID]) {
      //   HWriter.writeLines([
      //   "/*! @brief CCM32K OSC set for " + configName + " configuration.",
      //   " */"
      //   ], this.ccm32kConfigExternPosition[configID]);
      //   HWriter.write("extern const ccm32k_osc_config_t g_ccm32kOscConfig_" + prefixID + ";", this.ccm32kConfigExternPosition[configID]);
      // }
    }
  },
}
