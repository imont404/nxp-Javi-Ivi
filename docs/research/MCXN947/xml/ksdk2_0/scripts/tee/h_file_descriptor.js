    self.render = function() {
        // assembly collected sections and return final content of the tzm_config.h file
        var isMCXN9xx = ["MCXN946", "MCXN947"].indexOf(scriptApi.getProfile().getMcuInfo().getPartNumber()) > -1
        lines = []
        lines.push(sharedResources.notification);
        lines.push(self.head);
        lines.push(self.cppSection);
        //
        if (sharedResources.isEnabledSecurityCodeHardening()) {
            lines.push(isMCXN9xx? self.macroSection_mcxn9xx : self.macroSection);
        }
        //
        allFuncGroups = sharedResources.profile.getFunctionalGroups();
        allFuncGroups.forEach(function (funcGrp) {
            lines.push(self.initFuncComment(funcGrp.getName()));
            lines.push(self.initBoot(funcGrp.getIdPrefix()));
            //
            if (!LEGACY_SOURCE_NAMES) {
                if (self.isMpuCodeGenerationOn(mpu.getSecureMpuConfig(funcGrp)) || self.isMpuCodeGenerationOn(mpu.getNonSecureMpuConfig(funcGrp))) {
                    lines.push(self.initMPU(funcGrp.getIdPrefix()));
                }
                lines.push(self.initAHBSE(funcGrp.getIdPrefix()));
                lines.push(self.initTEE(funcGrp));
            }
        });
        //
        lines.push(self.initBootTEE);
        lines.push(self.tail);
        return lines.join("\n\n");
    };
